        "       - NSW: Green *= 1.03\n",
        "       - Vic: Clover *= 0.85\n",
        "       - WA: Clover *= 0.80, Dead *= 0.80, Green *= 0.97\n",
        "    3. Range Clipping to Training Bounds:\n",
        "       - Clover in [0, 71.7865], Dead in [0, 83.8407], Green in [0, 157.9836]\n",
        "    4. Recompute Physical Identities (GDM and Total).\n",
