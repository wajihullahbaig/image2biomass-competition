        "    y_true = np.array(y_true, dtype=float)\n",
        "    y_pred = np.array(y_pred, dtype=float)\n",
        "    w = np.array(weights, dtype=float)\n",
        "    if y_true.ndim == 1: y_true = y_true.reshape(-1, 5)\n",
        "    if y_pred.ndim == 1: y_pred = y_pred.reshape(-1, 5)\n",
